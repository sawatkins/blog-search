    def test_reindex_failure_backoff_status_and_retry_scope(self):
        succeeded, indexed = self.save()
        for attempt in range(1, 14):
            self.assertTrue(self.store.index_failed(indexed['page_id'], indexed['revision'], 'ES down'))
            row = self.query('SELECT *, EXTRACT(EPOCH FROM due_at - NOW()) AS delay FROM crawl_index_jobs')[0]
            self.assertEqual(attempt, row['attempts'])
            self.assertAlmostEqual(min(86400, 60 * 2 ** (attempt - 1)), float(row['delay']), delta=5)
        self.assertEqual([], self.store.index_batch())
        failed = self.claimed(name='failed')
        self.store.fail(failed, 'permanent', retryable=False)
        pending = self.claimed(name='pending')
        self.store.fail(pending, 'temporary')
        running = self.claimed(name='running')
        skipped = self.claimed(name='skipped')
        self.store.complete(skipped, skip_reason='skip')
        before = [self.row(job) for job in (succeeded, pending, running, skipped)]
        status = self.store.status()
        json.dumps(status)
        self.assertEqual(1, status['outbox'])
        self.assertEqual(1, status['outbox_failed'])
        self.assertEqual(1, status['counts']['page']['failed'])
        self.assertEqual(1, status['counts']['page']['skipped'])
        self.assertIsNotNone(status['latest_success'])
        self.assertEqual(2, self.store.retry_failed())
        self.assertEqual(before, [self.row(job) for job in (succeeded, pending, running, skipped)])
        self.assertEqual(indexed['revision'], self.store.index_batch()[0]['revision'])
        self.assertEqual(0, self.store.status()['outbox_failed'])
        self.assertEqual(1, self.store.queue_reindex())
        newer = self.store.index_batch()[0]
        self.assertGreater(newer['revision'], indexed['revision'])
        self.assertFalse(self.store.index_failed(indexed['page_id'], indexed['revision'], 'late failure'))
        self.assertEqual(1, self.query('SELECT COUNT(*) AS count FROM pages')[0]['count'])


