TEST_DATABASE_URL = os.environ.get('TEST_DATABASE_URL')


def claim_in_process(dsn, barrier, results):
    """Spawned workers construct independent connection pools."""
    try:
        with Store(dsn) as store:
            barrier.wait(timeout=15)
            results.put(store.claim())
    except Exception as error:
        results.put({'error': type(error).__name__})


@unittest.skipUnless(TEST_DATABASE_URL, 'TEST_DATABASE_URL is not set')
class StorageTests(unittest.TestCase):
    def setUp(self):
        self.schema = 'test_storage_' + uuid4().hex
        self.dsn = make_dsn(TEST_DATABASE_URL, options='-csearch_path=' + self.schema)
        self.connection = psycopg2.connect(self.dsn)
        self.connection.autocommit = True
        self.addCleanup(self.connection.close)
        self.query(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(self.schema)))
        self.addCleanup(self.drop_schema)
        self.store = Store(self.dsn)
        self.addCleanup(self.store.close)
        self.store.migrate()

    def drop_schema(self):
        # The identifier is generated by this test, never an environment-provided schema.
        self.query(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(self.schema)))

    def query(self, statement, parameters=()):
        with self.connection.cursor(cursor_factory=RealDictCursor) as cursor:
            cursor.execute(statement, parameters)
            return [dict(row) for row in cursor.fetchall()] if cursor.description else []

    def job(self, name='article', kind='page', **extra):
        return {'kind': kind, 'url': 'https://' + name + '.example/post', **extra}

    def page(self, url='https://article.example/post', **extra):
        return {'title': 'A post', 'url': url, 'fingerprint': 'first-fingerprint',
                'date': date(2026, 1, 2), 'text': 'The body of the post.', **extra}

    def claimed(self, **extra):
        self.store.enqueue([self.job(**extra)])
        return self.store.claim(1)[0]

    def row(self, job):
        return self.query('SELECT * FROM crawl_jobs WHERE id = %s', (job['id'],))[0]

    def make_due(self, job):
        self.query("UPDATE crawl_jobs SET due_at = NOW() - INTERVAL '1 second' WHERE id = %s",
                   (job['id'],))

    def expire(self, job):
        self.query("UPDATE crawl_jobs SET lease_until = NOW() - INTERVAL '1 second' WHERE id = %s",
                   (job['id'],))

    def save(self, page=None):
        job = self.claimed()
        self.assertTrue(self.store.complete(job, page=page or self.page()))
        return job, self.store.index_batch()[0]

    def assert_delay(self, job, seconds):
        row = self.query('SELECT EXTRACT(EPOCH FROM due_at - NOW()) AS delay FROM crawl_jobs WHERE id = %s',
                         (job['id'],))[0]
        self.assertAlmostEqual(float(row['delay']), seconds, delta=5)

    def test_explicit_migration_is_idempotent_and_preserves_existing_pages(self):
        self.query("""INSERT INTO pages (title, url, fingerprint, date, text)
                      VALUES ('Legacy', 'https://legacy.example/', 'legacy', '2020-01-01', 'Old text')""")
        before = self.query('SELECT * FROM pages')
        self.store.migrate()
        self.store.migrate()
        self.assertEqual(before, self.query('SELECT * FROM pages'))
        self.assertEqual([], self.store.index_batch())
        with self.assertRaises(psycopg2.IntegrityError):
            self.query("INSERT INTO pages (url, fingerprint) VALUES ('https://duplicate.example/', 'legacy')")
        self.query('DROP TABLE crawl_jobs')
        with Store(self.dsn):
            self.assertIsNone(self.query("SELECT to_regclass('crawl_jobs') AS table_name")[0]['table_name'])
        self.store.migrate()

    def test_dsn_resolution_and_context_closing(self):
        with patch('scraper.storage.ThreadedConnectionPool') as pool:
            with patch.dict(os.environ, {'DATABASE_URL': 'environment-dsn'}):
                Store('explicit-dsn')
                pool.assert_called_with(1, 4, dsn='explicit-dsn', connect_timeout=10)
                Store()
                pool.assert_called_with(1, 4, dsn='environment-dsn', connect_timeout=10)
            with patch.dict(os.environ, {}, clear=True):
                Store()
                pool.assert_called_with(1, 4, dsn='', connect_timeout=10)
        with Store(self.dsn) as store:
            self.assertEqual(1, store._pool.minconn)
            self.assertEqual(4, store._pool.maxconn)
            store.status()
        self.assertTrue(store._pool.closed)
        store.close()

    def test_connection_and_statement_timeouts_and_cancel_recovery(self):
        with self.store._transaction() as cursor:
            self.assertEqual('10', cursor.connection.get_dsn_parameters()['connect_timeout'])
            cursor.execute('SHOW statement_timeout')
            self.assertEqual('30s', cursor.fetchone()['statement_timeout'])
        with self.assertRaises(psycopg2.errors.QueryCanceled):
            with self.store._transaction() as cursor:
                cursor.execute("SET LOCAL statement_timeout = '20ms'")
                cursor.execute('SELECT pg_sleep(0.1)')
        self.assertEqual(1, self.store.enqueue([self.job()]))

    def test_dead_idle_connection_is_replaced_before_work(self):
        with self.store._transaction() as cursor:
            cursor.execute('SELECT pg_backend_pid() AS pid')
            old_pid = cursor.fetchone()['pid']
        self.query('SELECT pg_terminate_backend(%s)', (old_pid,))
        self.assertEqual(1, self.store.enqueue([self.job()]))
        with self.store._transaction() as cursor:
            cursor.execute('SELECT pg_backend_pid() AS pid')
            self.assertNotEqual(old_pid, cursor.fetchone()['pid'])
        self.assertEqual({}, self.store._pool._used)

    def test_connection_loss_during_completion_rolls_back_and_is_not_replayed(self):
        job = self.claimed()
        before = self.row(job)
        original = self.store._save_page
        def disconnect(cursor, page):
            result = original(cursor, page)
            self.query('SELECT pg_terminate_backend(%s)', (cursor.connection.get_backend_pid(),))
            return result
        with patch.object(self.store, '_save_page', side_effect=disconnect) as save:
            with self.assertRaises((psycopg2.OperationalError, psycopg2.InterfaceError)):
                self.store.complete(job, page=self.page(), links=[self.job('new')])
            self.assertEqual(1, save.call_count)
        self.assertEqual(before, self.row(job))
        self.assertEqual([], self.store.index_batch())
        self.assertEqual([], self.query('SELECT * FROM pages'))
        self.assertEqual(1, len(self.query('SELECT * FROM crawl_jobs')))
        self.assertTrue(self.store.complete(job, page=self.page()))

