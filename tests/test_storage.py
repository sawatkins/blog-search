    def test_claims_are_exclusive_across_processes_and_normalize_hosts(self):
        self.store.enqueue([self.job(str(number), url='https://SHARED.example./' + str(number))
                            for number in range(8)] + [self.job('other')])
        context = multiprocessing.get_context('spawn')
        barrier, results = context.Barrier(2), context.Queue()
        workers = [context.Process(target=claim_in_process, args=(self.dsn, barrier, results)) for _ in range(2)]
        try:
            for worker in workers:
                worker.start()
            batches = [results.get(timeout=25) for _ in workers]
            for batch in batches:
                self.assertIsInstance(batch, list)
            claimed = [job for batch in batches for job in batch]
            self.assertEqual(2, len(claimed))
            self.assertEqual({'shared.example', 'other.example'}, {job['host'] for job in claimed})
            self.assertEqual([], self.store.claim())
        finally:
            for worker in workers:
                worker.join(timeout=5)
                if worker.is_alive():
                    worker.terminate()
                    worker.join(timeout=5)
            results.close()
            results.join_thread()

