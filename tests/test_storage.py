    def test_failure_backoff_limits_retry_after_and_terminal_retries(self):
        job = self.claimed()
        for attempt in range(1, 9):
            self.assertEqual(attempt, job['attempts'])
            self.assertTrue(self.store.fail(job, 'temporary'))
            self.assert_delay(job, min(86400, 60 * 2 ** (attempt - 1)))
            self.assertEqual('failed' if attempt == 8 else 'pending', self.row(job)['status'])
            if attempt < 8:
                self.make_due(job)
                job = self.store.claim(1)[0]
        self.assertEqual([], self.store.claim())
        self.assertEqual(1, self.store.retry_failed())
        job = self.store.claim(1)[0]
        self.assertEqual(1, job['attempts'])
        self.store.fail(job, 'rate limited', retry_after=timedelta(days=10))
        self.assert_delay(job, 86400)
        self.make_due(job)
        self.query('UPDATE domains SET next_allowed_scrape = NOW() WHERE domain = %s', (job['host'],))
        job = self.store.claim(1)[0]
        self.store.fail(job, 'rate limited again', retry_after='7200')
        self.assert_delay(job, 7200)
        self.make_due(job)
        self.query('UPDATE domains SET next_allowed_scrape = NOW() WHERE domain = %s', (job['host'],))
        self.store.fail(self.store.claim(1)[0], 'permanent', retryable=False)
        self.assertEqual('failed', self.row(job)['status'])
        feed = self.claimed(name='feed', kind='feed')
        self.store.fail(feed, 'permanent feed failure', retryable=False)
        self.assertEqual('pending', self.row(feed)['status'])
        self.assert_delay(feed, 86400)
        self.make_due(feed)
        feed = self.store.claim(1)[0]
        self.query('UPDATE crawl_jobs SET attempts = 200 WHERE id = %s', (feed['id'],))
        self.store.fail(feed, 'still unavailable', retry_after=1)
        self.assertEqual('pending', self.row(feed)['status'])
        self.assert_delay(feed, 86400)

